import { expect, test } from '@playwright/test'
import { eur, ready, requestForm, url } from './helpers'

test.describe('request form (demo mode)', () => {
  test('validates required fields, keeps input and focuses the first problem', async ({ page }) => {
    await page.goto(url('yhteystiedot/'))
    await ready(page)
    const form = requestForm(page)
    await form.getByLabel('Sähköposti').fill('ei-osoite')
    await form.getByRole('button', { name: 'Lähetä tarjouspyyntö' }).click()
    await expect(form.getByText('Valitse, mitä palvelua pyyntö koskee.')).toBeVisible()
    await expect(form.getByText('Kirjoita nimesi.')).toBeVisible()
    await expect(form.getByText('Tarkista sähköpostiosoite')).toBeVisible()
    await expect(form.getByRole('alert')).toContainText('korjattavaa kohtaa')
    await expect(form.locator('input[name="topic"]').first()).toBeFocused()
    await expect(form.getByLabel('Sähköposti')).toHaveValue('ei-osoite')

    // a project description is required for site supervision; one contact method is required
    await form.getByText('Vastaava työnjohtaja tai valvonta', { exact: true }).click()
    await form.getByLabel('Sähköposti').fill('')
    await form.getByLabel('Nimi *').fill('Testi Asiakas')
    await form.getByRole('button', { name: 'Lähetä tarjouspyyntö' }).click()
    await expect(form.getByText('Kerro lyhyesti kohteesta tai hankkeesta.')).toBeVisible()
    await expect(form.getByText('Anna puhelinnumero tai sähköpostiosoite')).toBeVisible()
    await expect(form.getByLabel(/Kerro hankkeesta/)).toBeFocused()
  })

  test('submits nothing anywhere and says so', async ({ page }) => {
    const posts: string[] = []
    page.on('request', (r) => r.method() !== 'GET' && posts.push(r.url()))
    await page.goto(url('yhteystiedot/'))
    await ready(page)
    const form = requestForm(page)
    await form.getByText('Kuntotarkastus asuntokauppaan', { exact: true }).click()
    await form.getByLabel('Nimi *').fill('Testi Asiakas')
    await form.getByLabel('Puhelin').fill('040 123 4567')
    await form.getByRole('button', { name: 'Lähetä tarjouspyyntö' }).click()
    await expect(page.getByText('Demoversio – viestiä ei lähetetty.')).toBeVisible()
    expect(posts).toEqual([])
    const stored = await page.evaluate(() => localStorage.length + sessionStorage.length)
    expect(stored).toBe(0)
  })

  test('inspection: year of construction shows the published price in the summary', async ({ page }) => {
    await page.goto(url('yhteystiedot/?palvelu=kuntotarkastus'))
    await ready(page)
    const form = requestForm(page)
    await expect(form.locator('input[name="topic"][value="kuntotarkastus"]')).toBeChecked()
    const summary = page.getByRole('complementary', { name: 'Pyynnön yhteenveto' })
    await form.getByLabel('Rakennusvuosi').fill('2000')
    await expect(summary).toContainText(eur('950 €'))
    await form.getByLabel('Rakennusvuosi').fill('1985')
    await expect(summary).toContainText(eur('1 000 €'))
    await form.getByLabel('Rakennusvuosi').fill('2015')
    await expect(summary).toContainText(eur('900 €'))
    await form.getByLabel('Rakennusvuosi').fill('3020')
    await form.getByLabel('Nimi *').fill('Testi')
    await form.getByLabel('Puhelin').fill('0401234567')
    await form.getByRole('button', { name: 'Lähetä tarjouspyyntö' }).click()
    await expect(form.getByText('Tarkista rakennusvuosi')).toBeVisible()
  })

  test('laboratory order: specimen rows and calculated test date', async ({ page }) => {
    await page.goto(url('yhteystiedot/'))
    await ready(page)
    const form = requestForm(page)
    await form.getByText('Betonitestaus laboratoriossa', { exact: true }).click()
    await expect(form.getByText('Koekappale 1', { exact: true })).toBeVisible()
    await form.getByLabel('Valmistuspäivä').first().fill('2026-11-02')
    await expect(form.getByLabel('Koestusikä (vrk)').first()).toHaveValue('28')
    await expect(form.getByText(/Laskennallinen koestuspäivä:.*30\.11\.2026/)).toBeVisible()
    await form.getByRole('button', { name: 'Lisää koekappale' }).click()
    await expect(form.getByText('Koekappale 2', { exact: true })).toBeVisible()
    await expect(page.getByRole('complementary', { name: 'Pyynnön yhteenveto' })).toContainText('2 kpl')
    await form.getByRole('button', { name: 'Poista koekappale 2' }).click()
    await expect(form.getByText('Koekappale 2', { exact: true })).toHaveCount(0)
    await expect(form.getByRole('link', { name: /Tai lataa tilauslomake/ })).toHaveAttribute('href', /instokj_tilauslomake\.pdf$/)
  })

  test('service page CTA preselects the service', async ({ page }) => {
    await page.goto(url('palvelut/kosteusmittaus/'))
    await ready(page)
    await page.getByRole('link', { name: 'Tilaa betonin kosteusmittaus' }).click()
    await expect(page).toHaveURL(/yhteystiedot\/?\?palvelu=betonin-kosteusmittaus#tarjouspyynto/)
    await expect(page.locator('input[name="topic"][value="betonin-kosteusmittaus"]')).toBeChecked()
  })
})

